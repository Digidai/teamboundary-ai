import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const runtimePackages = ['hono', 'jose', 'react', 'react-dom', 'scheduler'];
const vendoredLicenseFallbacks = new Map();
const checkOnly = process.argv.includes('--check');
const sections = [];

for (const name of runtimePackages) {
  const directory = new URL(`node_modules/${name}/`, root);
  const metadata = JSON.parse(await readFile(new URL('package.json', directory), 'utf8'));
  const entries = await readdir(directory);
  let licenseFilename = entries
    .filter((entry) => /^(?:licen[cs]e|copying)(?:\.[a-z0-9-]+)?$/i.test(entry))
    .sort((left, right) => left.localeCompare(right))[0];
  const fallback = vendoredLicenseFallbacks.get(name);
  if (!licenseFilename && !fallback) {
    throw new Error(`${name} does not contain a distributable license file`);
  }
  if (fallback && metadata.version !== fallback.version) {
    throw new Error(`${name}@${metadata.version} requires a newly reviewed vendored license`);
  }
  const licenseSource = licenseFilename ? new URL(licenseFilename, directory) : fallback.url;
  licenseFilename ||= `vendored/${fallback.url.pathname.split('/').at(-1)}`;
  const licenseText = `${(await readFile(licenseSource, 'utf8')).trim()}\n`;
  const licenseSha256 = createHash('sha256').update(licenseText).digest('hex');
  if (fallback && licenseSha256 !== fallback.sha256) {
    throw new Error(`${name} vendored license does not match its reviewed SHA-256`);
  }
  const repository = normalizeRepository(metadata.repository);
  sections.push(
    [
      '='.repeat(80),
      `Package: ${name}@${metadata.version}`,
      `Declared license: ${metadata.license || 'UNKNOWN'}`,
      `Source: ${repository || `https://www.npmjs.com/package/${encodeURIComponent(name)}`}`,
      `License file: ${licenseFilename}`,
      ...(fallback ? [`License provenance: ${fallback.provenance}`] : []),
      `License SHA-256: ${licenseSha256}`,
      '-'.repeat(80),
      licenseText.trimEnd(),
    ].join('\n'),
  );
}

const output = `${[
  'THIRD-PARTY LICENSES',
  '',
  'Generated by scripts/generate-third-party-licenses.mjs from the exact installed runtime',
  'dependency versions. Do not edit this file by hand. Development-only tools are inventoried',
  'in package-lock.json and THIRD_PARTY_NOTICES.md but are not part of the deployed runtime.',
  '',
  ...sections,
].join('\n')}\n`;

await writeOrCheck(new URL('THIRD_PARTY_LICENSES.txt', root), output);
await writeOrCheck(new URL('public/THIRD_PARTY_LICENSES.txt', root), output);
await mirror('LICENSE', 'public/LICENSE.txt');
await mirror('NOTICE', 'public/NOTICE.txt');

console.log(
  `${checkOnly ? 'Validated' : 'Generated'} complete license texts for ${runtimePackages.length} runtime packages.`,
);

async function mirror(source, target) {
  await writeOrCheck(new URL(target, root), await readFile(new URL(source, root), 'utf8'));
}

async function writeOrCheck(target, expected) {
  if (!checkOnly) {
    await writeFile(target, expected);
    return;
  }
  let actual;
  try {
    actual = await readFile(target, 'utf8');
  } catch {
    throw new Error(`${target.pathname} is missing; run npm run license:bundle`);
  }
  if (actual !== expected) {
    throw new Error(`${target.pathname} is stale; run npm run license:bundle`);
  }
}

function normalizeRepository(value) {
  const repository = typeof value === 'string' ? value : value?.url;
  if (!repository) return '';
  return repository
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/\.git$/, '');
}
